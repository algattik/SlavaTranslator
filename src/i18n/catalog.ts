export function normalizeUiLocale(value: string): UiLocale {
  const normalized = value.replaceAll("_", "-").toLocaleLowerCase("en");
  if (normalized.startsWith("pt")) {
    return "pt-BR";
  }
  if (normalized.startsWith("zh")) {
    return "zh-CN";
  }
  return (
    UI_LOCALES.find(
      (locale) => locale.toLocaleLowerCase("en") === normalized,
    ) ??
    UI_LOCALES.find(
      (locale) =>
        locale.split("-")[0]?.toLocaleLowerCase("en") ===
        normalized.split("-")[0],
    ) ??
    "en"
  );
}

export function resolveUiLocale(
  preference: UiLocalePreference,
  browserUiLanguage: string,
): UiLocale {
  return preference === "auto"
    ? normalizeUiLocale(browserUiLanguage)
    : preference;
}

export function message(
  locale: UiLocale,
  key: MessageKey,
  substitutions: Record<string, string | number> = {},
): string {
  let value =
    locale === "en"
      ? ENGLISH_MESSAGES[key]
      : (MESSAGE_OVERRIDES[locale][key] ?? ENGLISH_MESSAGES[key]);
  for (const [name, substitution] of Object.entries(substitutions)) {
    value = value.replaceAll(`{${name}}`, String(substitution));
  }
  return value;
}

export function grammarLabel(locale: UiLocale, tag: GrammarTag): string {
  return (
    GRAMMAR_LABELS[locale][tag] ??
    GRAMMAR_LABELS.en[tag] ??
    tag.replaceAll("-", " ")
  );
}

export function definitionErrorMessage(
  locale: UiLocale,
  code: DefinitionErrorCode,
): string {
  return ERROR_MESSAGES[locale][code] ?? ERROR_MESSAGES.en[code] ?? code;
}

export function aspectLabel(locale: UiLocale, aspect: VerbAspect): string {
  return message(
    locale,
    aspect === "imperfective"
      ? "aspectImperfective"
      : aspect === "perfective"
        ? "aspectPerfective"
        : "aspectBiaspectual",
  );
}

export function localeDirection(locale: UiLocale): "ltr" | "rtl" {
  return locale === "ar" || locale === "he" ? "rtl" : "ltr";
}
